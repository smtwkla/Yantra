"""The schema docs' pure core (S078): catalogue rows in; the schema dict, the texts of
docs/schema/schema.json and docs/schema/schema-data.js, the check results and the outcome
(exit code and lines) out.  No database, no files, no clock; stdlib only.

The shell (schema_docs.py) builds a fresh database from backend/local_db.py _MIGRATIONS,
reads information_schema into plain dicts and passes them here.  Everything that depends on
the server's way of printing is normalised here (S078 brief § 5.2), so the files do not
change with the server version.
"""

import json
import re

SCHEMA_JSON = "docs/schema/schema.json"
SCHEMA_DATA_JS = "docs/schema/schema-data.js"
NOTES_JSON = "docs/schema/notes.json"
COMMAND = r"tooling\schema-docs.bat"

LOCAL_HOSTS = ("localhost", "127.0.0.1")   # as tooling/e2e/e2e_backend.py (copied: it imports the app)
DATABASE_SUFFIX = "_schemadocs"

NOTE = (f"Generated by {COMMAND} write from backend/local_db.py _MIGRATIONS. "
        f"Do not edit; edit {NOTES_JSON} and run the command.")
DATA_JS_HEADER = (f"// Generated by {COMMAND} write from {SCHEMA_JSON} and {NOTES_JSON}. Do not edit.")

INTEGER_TYPES = ("tinyint", "smallint", "mediumint", "int", "bigint")
_INT_WIDTH = re.compile(r"^(" + "|".join(INTEGER_TYPES) + r")\(\d+\)")
CUT = 120   # the longest piece of a stale line shown in a message

EXIT_PASSED, EXIT_FAILED, EXIT_NOT_COMPLETED = 0, 1, 2
NOT_COMPLETED_LINE = "Schema docs: not completed"


# ---------------------------------------------------------------------------
# Normalising the catalogue (§ 5.2)
# ---------------------------------------------------------------------------

def normalise_type(column_type):
    """COLUMN_TYPE in lower case without an integer type's display width: int(11) -> int,
    int(10) unsigned -> int unsigned.  Every other type as the server gives it."""
    return _INT_WIDTH.sub(r"\1", column_type.lower())


def normalise_default(value):
    """None for no default and for DEFAULT NULL (MariaDB gives SQL NULL or the text NULL);
    any other value as the server's text."""
    if value is None or value == "NULL":
        return None
    return str(value)


def _sorted_rows(rows, *keys):
    return sorted(rows, key=lambda r: tuple(r[k] for k in keys))


def build_schema(catalogue, migration):
    """The schema dict from the five row sets (§ 5.2) and the migration number.

    catalogue: {"tables", "columns", "statistics", "foreign_keys", "checks"}, each a list of
    dicts with the information_schema column names the shell reads."""
    names = sorted(r["TABLE_NAME"] for r in catalogue["tables"])
    tables = {name: {"columns": [], "primary_key": [], "foreign_keys": [], "indexes": [], "checks": []}
              for name in names}

    indexes = {}   # (table, index) -> {"unique": bool, "columns": [...]}
    for row in _sorted_rows(catalogue["statistics"], "TABLE_NAME", "INDEX_NAME", "SEQ_IN_INDEX"):
        if row["TABLE_NAME"] not in tables:
            continue
        column = row["COLUMN_NAME"]
        if row.get("SUB_PART") is not None:
            column = f"{column}({row['SUB_PART']})"
        entry = indexes.setdefault((row["TABLE_NAME"], row["INDEX_NAME"]),
                                   {"unique": int(row["NON_UNIQUE"]) == 0, "columns": []})
        entry["columns"].append(column)

    foreign_keys = {}   # (table, constraint) -> dict
    for row in _sorted_rows(catalogue["foreign_keys"], "TABLE_NAME", "CONSTRAINT_NAME", "ORDINAL_POSITION"):
        if row["TABLE_NAME"] not in tables:
            continue
        entry = foreign_keys.setdefault((row["TABLE_NAME"], row["CONSTRAINT_NAME"]), {
            "name": row["CONSTRAINT_NAME"], "columns": [], "references": row["REFERENCED_TABLE_NAME"],
            "ref_columns": [], "required": True, "on_delete": row["DELETE_RULE"], "on_update": row["UPDATE_RULE"]})
        entry["columns"].append(row["COLUMN_NAME"])
        entry["ref_columns"].append(row["REFERENCED_COLUMN_NAME"])

    for (table, index), entry in sorted(indexes.items()):
        if index == "PRIMARY":
            tables[table]["primary_key"] = entry["columns"]
        else:
            tables[table]["indexes"].append({"name": index, "unique": entry["unique"], "columns": entry["columns"]})

    nullable = {}
    for row in _sorted_rows(catalogue["columns"], "TABLE_NAME", "ORDINAL_POSITION"):
        table = row["TABLE_NAME"]
        if table not in tables:
            continue
        nullable[(table, row["COLUMN_NAME"])] = row["IS_NULLABLE"] == "YES"
        tables[table]["columns"].append({
            "name": row["COLUMN_NAME"],
            "type": normalise_type(row["COLUMN_TYPE"]),
            "null": row["IS_NULLABLE"] == "YES",
            "default": normalise_default(row["COLUMN_DEFAULT"]),
            "key": "",
            "extra": (row["EXTRA"] or "").lower(),
        })

    for (table, _name), entry in sorted(foreign_keys.items()):
        entry["required"] = not any(nullable.get((table, c), False) for c in entry["columns"])
        tables[table]["foreign_keys"].append(entry)

    for row in _sorted_rows(catalogue["checks"], "TABLE_NAME", "CONSTRAINT_NAME"):
        if row["TABLE_NAME"] not in tables:
            continue
        tables[row["TABLE_NAME"]]["checks"].append({
            "name": row["CONSTRAINT_NAME"], "level": row["LEVEL"].lower(), "clause": row["CHECK_CLAUSE"]})

    for table in tables.values():
        _tag_keys(table)
    return {"_note": NOTE, "migration": migration, "tables": tables}


def _tag_keys(table):
    """A column's key: PK (in the primary key), FK (in any foreign key), UK (a unique index
    other than PRIMARY has this column alone), joined by ','."""
    in_fk = {c for fk in table["foreign_keys"] for c in fk["columns"]}
    single_unique = {ix["columns"][0] for ix in table["indexes"] if ix["unique"] and len(ix["columns"]) == 1}
    for column in table["columns"]:
        name = column["name"]
        tags = [tag for tag, holds in (("PK", name in table["primary_key"]), ("FK", name in in_fk),
                                       ("UK", name in single_unique)) if holds]
        column["key"] = ",".join(tags)


# ---------------------------------------------------------------------------
# The texts (§ 4.1, § 4.2)
# ---------------------------------------------------------------------------

def _one_line(value):
    return json.dumps(value, ensure_ascii=False)


def _list_lines(key, items, indent):
    """A list key: [] on its own line when empty, else one item per line."""
    pad = " " * indent
    if not items:
        return [f"{pad}{_one_line(key)}: []"]
    lines = [f"{pad}{_one_line(key)}: ["]
    lines += [f"{pad}  {_one_line(item)}" + ("," if i < len(items) - 1 else "") for i, item in enumerate(items)]
    lines.append(f"{pad}]")
    return lines


def _join_members(blocks):
    """Joins the member blocks of an object, a comma after each block but the last."""
    lines = []
    for i, block in enumerate(blocks):
        block = list(block)
        if i < len(blocks) - 1:
            block[-1] += ","
        lines += block
    return lines


def _schema_lines(schema):
    table_blocks = []
    for name, table in schema["tables"].items():
        members = [_list_lines(key, table[key], 6) if key != "primary_key"
                   else [f"      {_one_line(key)}: {_one_line(table[key])}"]
                   for key in ("columns", "primary_key", "foreign_keys", "indexes", "checks")]
        table_blocks.append([f"    {_one_line(name)}: {{", *_join_members(members), "    }"])
    tables = ["  \"tables\": {}"] if not table_blocks else ["  \"tables\": {", *_join_members(table_blocks), "  }"]
    return ["{", f"  \"_note\": {_one_line(schema['_note'])},", f"  \"migration\": {_one_line(schema['migration'])},",
            *tables, "}"]


def schema_json_text(schema):
    """docs/schema/schema.json: one column, key, index or check per line; LF, one final newline."""
    return "\n".join(_schema_lines(schema)) + "\n"


def _notes_lines(notes):
    """notes.json in the fixed layout: one area, one table, one planned group per line."""
    areas = notes.get("areas") or []
    tables = notes.get("tables") or {}
    planned = notes.get("planned") or []
    table_lines = [f"    {_one_line(name)}: {_one_line(entry)}" + ("," if i < len(tables) - 1 else "")
                   for i, (name, entry) in enumerate(tables.items())]
    tables_block = (["  \"tables\": {}"] if not table_lines else ["  \"tables\": {", *table_lines, "  }"])
    members = [
        [f"  \"overview_note\": {_one_line(notes.get('overview_note', ''))}"],
        _list_lines("areas", areas, 2),
        tables_block,
        [f"  \"planned_note\": {_one_line(notes.get('planned_note', ''))}"],
        _list_lines("planned", planned, 2),
    ]
    return ["{", *_join_members(members), "}"]


def data_js_text(schema_text, notes):
    """docs/schema/schema-data.js: the JSON text unchanged and the notes, as a classic script a
    page opened from disk may load."""
    return "\n".join([DATA_JS_HEADER, "window.YANTRA_SCHEMA = " + schema_text.rstrip("\n") + ";",
                      "window.YANTRA_SCHEMA_NOTES = " + "\n".join(_notes_lines(notes)) + ";"]) + "\n"


# ---------------------------------------------------------------------------
# The notes and the checks (§ 5.3)
# ---------------------------------------------------------------------------

def parse_notes(text):
    """(notes, None), or (None, the problem) when the file is missing or not a JSON object."""
    if text is None:
        return None, f"{NOTES_JSON} is missing. Restore it from git, then run the command again."
    try:
        notes = json.loads(text)
    except json.JSONDecodeError as exc:
        return None, f"{NOTES_JSON} is not valid JSON: {exc}. Fix the file, then run the command again."
    if not isinstance(notes, dict):
        return None, f"{NOTES_JSON} is not valid JSON: the file must hold one object {{...}}. Fix the file, then run the command again."
    return notes, None


def _cut(text):
    return text if len(text) <= CUT else text[:CUT] + "…"


def file_problems(path, on_disk, generated):
    """Checks 1 and 2: the file on disk equals the generated text (CRLF read as LF)."""
    action = f"Run {COMMAND} write and commit the result."
    if on_disk is None:
        return [f"{path} is missing. {action}"]
    disk_text = on_disk.replace("\r\n", "\n")
    new_text = generated.replace("\r\n", "\n")
    if disk_text == new_text:
        return []
    disk_lines, new_lines = disk_text.split("\n"), new_text.split("\n")
    end = "(end of file)"
    for number in range(1, max(len(disk_lines), len(new_lines)) + 1):
        disk = disk_lines[number - 1] if number <= len(disk_lines) else end
        new = new_lines[number - 1] if number <= len(new_lines) else end
        if disk != new:
            # the empty piece after a final newline is no line of its own
            if disk == "" and number == len(disk_lines):
                disk = end
            if new == "" and number == len(new_lines):
                new = end
            if disk == new:
                return [f"{path} is stale: the final newline differs. {action}"]
            return [f"{path} is stale: line {number} differs (on disk: {_cut(disk)}; generated: {_cut(new)}). {action}"]
    return [f"{path} is stale. {action}"]   # not reached: unequal texts differ in some line


def notes_problems(schema, notes):
    """Check 3: the notes match the built tables."""
    problems = []
    areas = [a.get("name") if isinstance(a, dict) else None for a in (notes.get("areas") or [])]
    area_names = [a for a in areas if a]
    for name in sorted({a for a in area_names if area_names.count(a) > 1}):
        problems.append(f"{NOTES_JSON} names area \"{name}\" twice under \"areas\". Give each area its own name.")
    tables = notes.get("tables") or {}
    built = schema["tables"]
    one_of = ", ".join(area_names)
    for name in built:
        if name not in tables:
            problems.append(f"{NOTES_JSON} has no line for table {name}. Add \"{name}\": {{\"area\": \"<one of: "
                            f"{one_of}>\", \"holds\": \"<what it holds>\"}} under \"tables\", then run {COMMAND} write.")
    for name in sorted(tables):
        entry = tables[name] if isinstance(tables[name], dict) else {}
        if name not in built:
            problems.append(f"{NOTES_JSON} has a line for table {name}, which is not built. "
                            f"Remove the line, or move it to \"planned\".")
            continue
        area = entry.get("area")
        if area not in area_names:
            shown = f"\"{area}\"" if area else "(none)"
            problems.append(f"{NOTES_JSON}: table {name} names area {shown}, which is not in \"areas\".")
        holds = entry.get("holds")
        if not isinstance(holds, str) or not holds.strip():
            problems.append(f"{NOTES_JSON}: table {name} has no \"holds\" text. Write what it holds.")
    return problems


def planned_problems(schema, notes):
    """Check 4: no planned table is built."""
    problems = []
    for group in notes.get("planned") or []:
        for name in (group.get("tables") or []) if isinstance(group, dict) else []:
            if name in schema["tables"]:
                problems.append(f"{NOTES_JSON} lists {name} under \"planned\", but it is built. "
                                f"Move it to \"tables\" with its area.")
    return problems


def run_checks(schema, notes, on_disk, generated):
    """The four checks, in order, as (passed, problems).  on_disk and generated map
    SCHEMA_JSON and SCHEMA_DATA_JS to their texts (on_disk: None when missing)."""
    results = []
    for problems in (file_problems(SCHEMA_JSON, on_disk.get(SCHEMA_JSON), generated[SCHEMA_JSON]),
                     file_problems(SCHEMA_DATA_JS, on_disk.get(SCHEMA_DATA_JS), generated[SCHEMA_DATA_JS]),
                     notes_problems(schema, notes),
                     planned_problems(schema, notes)):
        results.append((not problems, problems))
    return results


def checks_without_notes(notes_problem):
    """The four results when notes.json cannot be read: checks 3 and 4 fail on it, and checks
    1 and 2 are not run (schema-data.js needs the notes) and count as failed."""
    return [(False, [f"{SCHEMA_JSON} and {SCHEMA_DATA_JS} were not checked: {NOTES_JSON} could not be read."]),
            (False, []), (False, [notes_problem]), (False, [])]


def files_to_write(schema, notes):
    """The generated texts by path; nothing when the notes could not be read."""
    if notes is None:
        return {}
    schema_text = schema_json_text(schema)
    return {SCHEMA_JSON: schema_text, SCHEMA_DATA_JS: data_js_text(schema_text, notes)}


# ---------------------------------------------------------------------------
# The guard, the not-completed messages and the outcome (§ 5.1, § 5.5)
# ---------------------------------------------------------------------------

def check_target(host, database):
    """None when the database may be dropped and rebuilt: a local host and a name ending in
    _schemadocs; else the refusal."""
    if host not in LOCAL_HOSTS:
        return (f"The schema docs were not built: refusing database host {host}; "
                f"the schema docs database must be local ({', '.join(LOCAL_HOSTS)}).")
    if not (database or "").endswith(DATABASE_SUFFIX):
        return (f"The schema docs were not built: refusing database {database}; "
                f"the schema docs database's name must end in {DATABASE_SUFFIX}.")
    return None


def unreachable_message(detail):
    return (f"The schema docs were not built. The dev database cannot be reached: {detail}. "
            r"Start it with tooling\dev\dev-db-up.bat, then run the command again.")


def create_refused_message(database):
    return (f"The schema docs were not built. The database user may not create {database}. "
            r"Run tooling\run-backend-tests.bat once (it grants the test databases), then run the command again.")


def migration_failed_message(detail):
    return (f"The schema docs were not built. The migrations could not be applied: {detail}. "
            "Fix the migration in backend/local_db.py, then run the command again.")


LOCK_TIMEOUT_MESSAGE = ("The schema docs were not built. Another schema docs run with the same run name is still "
                        "running. Wait for it, or set YANTRA_TEST_RUN to another name.")


def version_mismatch_message(built, latest):
    return (f"The schema docs were not built. The built database is at migration v{built}, but "
            f"backend/local_db.py LATEST_VERSION is v{latest}: a migration was skipped.")


def usage_message():
    return f"Usage: {COMMAND} write|check"


def outcome(migration, results=None, not_completed=None):
    """(exit code, lines).  not_completed: the message of a run that could not check (exit 2);
    else results: the four (passed, problems) of run_checks or checks_without_notes."""
    if not_completed is not None:
        return EXIT_NOT_COMPLETED, [not_completed, NOT_COMPLETED_LINE]
    lines = [problem for _passed, problems in results for problem in problems]
    passed = sum(1 for ok, _problems in results if ok)
    failed = len(results) - passed
    count = f"Schema docs at migration v{migration}: {passed} passed" + (f", {failed} failed" if failed else "")
    return (EXIT_FAILED if failed else EXIT_PASSED), [*lines, count]
